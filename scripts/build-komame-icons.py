"""Import the ordered, monochrome Komame catalog from a local checkout."""

import argparse
import json
from pathlib import Path
import re
import xml.etree.ElementTree as ET

OUTPUT = Path(__file__).resolve().parents[1] / "dist" / "komame-icons.mjs"
NS = "{http://www.w3.org/2000/svg}"
SVG_STYLE = {
    "fill": "none",
    "stroke": "#000",
    "stroke-width": "3.2",
    "stroke-linecap": "round",
    "stroke-linejoin": "round",
}


def load_icon(source, category, name, entry):
    path = f"labels/{category}/{name}.svg"
    if not re.fullmatch(r"[a-z0-9-]+/[a-z0-9-]+", f"{category}/{name}") or entry["path"] != path:
        raise ValueError(f"Invalid Komame icon entry: {category}/{name}")
    root = ET.parse(source / path).getroot()
    if root.tag != NS + "svg" or root.attrib.get("viewBox") != "0 0 48 48":
        raise ValueError(f"Unexpected SVG viewBox in {path}")
    title, drawing = root
    if title.tag != NS + "title" or title.text != entry["label"] or drawing.tag != NS + "path":
        raise ValueError(f"Unexpected SVG contents in {path}")
    attributes = drawing.attrib.copy()
    commands = attributes.pop("d")
    if len(drawing) or attributes != SVG_STYLE or not re.fullmatch(r"[Mm][0-9A-Za-z., +\-]+", commands):
        raise ValueError(f"Unexpected drawing format in {path}")
    return [f"komame/{category}/{name}", entry["label"], commands]


def build(source):
    catalog = json.loads((source / "labels.json").read_text(encoding="utf-8"))
    if len(catalog) != 12 or any(len(group["icons"]) != 30 for group in catalog.values()):
        raise ValueError("Expected 12 Komame categories with 30 icons each")
    encode = lambda value: json.dumps(value, ensure_ascii=False)
    lines = [
        "// Generated by scripts/build-komame-icons.py from blair-ko/komame-icons labels.json and SVGs.",
        "export const komameGroups = [",
    ]
    for key, group in catalog.items():
        lines.append(f"  {{id:{encode(key)}, label:{encode(group['label'])}, icons:[")
        lines.extend(f"    {encode(load_icon(source, key, name, entry))}," for name, entry in group["icons"].items())
        lines.append("  ]},")
    lines.extend([
        "];",
        "",
        "export const komameIcons = Object.fromEntries(komameGroups.flatMap(({icons})=>",
        "  icons.map(([key,label,path])=>[key,{label,path}])));",
    ])
    OUTPUT.write_text("\n".join(lines) + "\n", encoding="utf-8")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path, help="Path to the Komame Icons checkout")
    build(parser.parse_args().source)
